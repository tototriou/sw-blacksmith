// Les phrases qui portent une valeur (un nom de passif) : un motif chacune.
const MOTIFS_DEGATS_EN: readonly { motif: RegExp; anglais: (m: RegExpExecArray) => string }[] = [
  {
    motif: /^(.+) se déclenche à la suite de ce sort \(probabilité du jeu non tirée\)$/,
    anglais: (m) => `${m[1]} triggers following this skill (in-game chance not rolled)`,
  },
];

// La phrase dans la langue de l'écran. Une phrase sans entrée (un nom de sort,
// déjà celui du jeu anglais) s'affiche telle quelle.
export function phraseDegats(fr: string, langue: Langue): string {
  if (langue === 'fr') return fr;
  const directe = PHRASES_DEGATS_EN[fr];
  if (directe !== undefined) return directe;
  for (const { motif, anglais } of MOTIFS_DEGATS_EN) {
    const m = motif.exec(fr);
    if (m) return anglais(m);
  }
  return fr;
}
